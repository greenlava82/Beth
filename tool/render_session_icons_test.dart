// Renders the band sync session icon shapes for the CYD follower
// (firmware/cyd-follower/src/session_icons.h) from the same Material icons
// the app shows (bandSyncIconGlyphs).
//
// It's written as a test so it can use Flutter's canvas without a device:
//
//   flutter test tool/render_session_icons_test.dart
//
// Each shape becomes a 4-bit alpha mask (two pixels per byte, high nibble
// first, rows padded to whole bytes) that the firmware tints with the
// icon's colour.
import 'dart:io';
import 'dart:typed_data';
import 'dart:ui' as ui;

import 'package:flutter/widgets.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:beth/band_sync_icon.dart';
import 'package:beth/band_sync_icon_view.dart';

const _outPath = 'firmware/cyd-follower/src/session_icons.h';

/// Glyph sizes in pixels: the leader picker's rows and the follower header.
const _sizes = {'Large': 26, 'Small': 16};

String _flutterRoot() {
  final env = Platform.environment['FLUTTER_ROOT'];
  if (env != null) return env;
  // flutter_tester lives in <root>/bin/cache/artifacts/engine/<platform>/.
  var dir = File(Platform.resolvedExecutable).parent;
  while (!File('${dir.path}/bin/flutter').existsSync()) {
    if (dir.parent.path == dir.path) {
      throw StateError('Can\'t find the Flutter SDK; set FLUTTER_ROOT');
    }
    dir = dir.parent;
  }
  return dir.path;
}

Future<void> _loadMaterialIcons() async {
  final path =
      '${_flutterRoot()}/bin/cache/artifacts/material_fonts/'
      'MaterialIcons-Regular.otf';
  final bytes = File(path).readAsBytesSync();
  final loader = FontLoader('MaterialIcons')
    ..addFont(Future.value(ByteData.view(bytes.buffer)));
  await loader.load();
}

/// The glyph's alpha, 0..15 per pixel, row by row.
Future<List<int>> _renderMask(IconData icon, int size) async {
  final rec = ui.PictureRecorder();
  final canvas = Canvas(rec);
  final painter = TextPainter(
    textDirection: TextDirection.ltr,
    text: TextSpan(
      text: String.fromCharCode(icon.codePoint),
      style: TextStyle(
        fontFamily: icon.fontFamily,
        fontSize: size.toDouble(),
        height: 1,
        color: const Color(0xFFFFFFFF),
      ),
    ),
  )..layout();
  painter.paint(
    canvas,
    Offset((size - painter.width) / 2, (size - painter.height) / 2),
  );
  final img = await rec.endRecording().toImage(size, size);
  final data = await img.toByteData(format: ui.ImageByteFormat.rawRgba);
  final rgba = data!.buffer.asUint8List();
  return [for (var i = 0; i < size * size; i++) (rgba[i * 4 + 3] + 8) ~/ 17];
}

List<int> _pack4(List<int> alpha, int size) {
  final rowBytes = (size + 1) ~/ 2;
  final out = List<int>.filled(rowBytes * size, 0);
  for (var y = 0; y < size; y++) {
    for (var x = 0; x < size; x++) {
      final a = alpha[y * size + x];
      out[y * rowBytes + x ~/ 2] |= x.isEven ? a << 4 : a;
    }
  }
  return out;
}

String _hex2(int v) => '0x${v.toRadixString(16).padLeft(2, '0')}';

void main() {
  test('render session icons for the CYD', () async {
    await _loadMaterialIcons();
    expect(bandSyncIconGlyphs.length, bandSyncIconShapes.length);

    final b = StringBuffer()
      ..writeln('// Generated by tool/render_session_icons_test.dart. Do not')
      ..writeln('// edit. The band sync session icon shapes as 4-bit alpha')
      ..writeln('// masks: two pixels per byte, high nibble first, each row')
      ..writeln('// padded to whole bytes. Index = shape (bandsync::Icon).')
      ..writeln('#pragma once')
      ..writeln()
      ..writeln('#include <stdint.h>')
      ..writeln()
      ..writeln(
        'constexpr int kSessionIconShapes = ${bandSyncIconShapes.length};',
      );
    for (final MapEntry(key: name, value: size) in _sizes.entries) {
      final rowBytes = (size + 1) ~/ 2;
      final masks = <List<int>>[];
      for (final glyph in bandSyncIconGlyphs) {
        final alpha = await _renderMask(glyph, size);
        // A blank mask means the icon font didn't load.
        expect(alpha.where((a) => a > 8).length, greaterThan(size));
        masks.add(_pack4(alpha, size));
      }
      b
        ..writeln()
        ..writeln('constexpr int kSessionIcon${name}Size = $size;')
        ..writeln(
          'static const uint8_t kSessionIcon$name'
          '[kSessionIconShapes][${rowBytes * size}] = {',
        );
      for (var i = 0; i < masks.length; i++) {
        b.writeln('    {  // ${bandSyncIconShapes[i]}');
        for (var r = 0; r < masks[i].length; r += 16) {
          b.writeln(
            '        ${masks[i].skip(r).take(16).map(_hex2).join(', ')},',
          );
        }
        b.writeln('    },');
      }
      b.writeln('};');
    }
    File(_outPath).writeAsStringSync(b.toString());
  });
}
