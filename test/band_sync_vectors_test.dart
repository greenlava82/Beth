// Shared test vectors for other band sync implementations (the CYD follower
// firmware in firmware/cyd-follower). The header is generated from the real
// encoder, so the firmware's decoder is tested against exactly what the app
// broadcasts.
//
// If the protocol changes, regenerate with:
//   UPDATE_VECTORS=1 flutter test test/band_sync_vectors_test.dart

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:scbeatwiz/band_sync_protocol.dart';
import 'package:scbeatwiz/tempo_drift.dart';

const _headerPath = 'firmware/cyd-follower/test/band_sync_vectors.h';

class _Vector {
  _Vector(this.name, this.uuid, this.state);
  final String name;

  /// As the app hands it to the platform: byte 0 first.
  final String uuid;

  /// The decoded state, or null if a decoder must reject it.
  final BandSyncState? state;
}

List<_Vector> _vectors() {
  const states = {
    'full': BandSyncState(
      sessionId: 0x4F2A,
      sequence: 200,
      metronomePlaying: true,
      drift: DriftLevel.drifting,
      rushing: true,
      songIndex: 3,
      targetBpm: 118,
      detectedBpm: 121.4,
      confidence: 0.62,
      detailsVersion: 0xBEEF,
    ),
    'empty_free_running': BandSyncState(sessionId: 1, freeRunning: true),
    'on_tempo_dragging': BandSyncState(
      sessionId: 0xFFFF,
      sequence: 255,
      drift: DriftLevel.onTempo,
      songIndex: 0,
      targetBpm: 80,
      detectedBpm: 79.6,
      confidence: 1,
      detailsVersion: 1,
    ),
    'off_fast': BandSyncState(
      sessionId: 0x0100,
      sequence: 7,
      drift: DriftLevel.off,
      songIndex: 254,
      targetBpm: 240,
      detectedBpm: 6553.5,
      confidence: 0.2,
    ),
  };
  final out = <_Vector>[
    for (final e in states.entries)
      _Vector(
        e.key,
        encodeBandSyncUuid(e.value),
        decodeBandSyncPayload(encodeBandSyncPayload(e.value)),
      ),
  ];

  final good = encodeBandSyncPayload(states['full']!);
  String mutate(void Function(List<int>) f) {
    final b = List<int>.of(good);
    f(b);
    return bandSyncPayloadToUuid(b);
  }

  out.addAll([
    _Vector('bad_check', mutate((b) => b[10] ^= 0x01), null),
    _Vector('wrong_magic', mutate((b) => b[0] = 0x00), null),
    _Vector(
      'newer_version',
      mutate((b) {
        b[2] = bandSyncProtocolVersion + 1;
        // Keep the check byte valid so only the version is wrong.
        var x = 0xA5;
        for (var i = 0; i < 15; i++) {
          x ^= b[i];
        }
        b[15] = x;
      }),
      null,
    ),
    // The leader's fixed GATT service UUID isn't a payload.
    _Vector('gatt_service', bandSyncServiceUuid, null),
  ]);
  return out;
}

String _hex(int v) => '0x${v.toRadixString(16).padLeft(2, '0').toUpperCase()}';

String _cBool(bool b) => b ? 'true' : 'false';

int _drift(DriftLevel? d) => switch (d) {
  null => 0,
  DriftLevel.onTempo => 1,
  DriftLevel.drifting => 2,
  DriftLevel.off => 3,
};

String renderHeader() {
  final b = StringBuffer()
    ..writeln('// Generated by test/band_sync_vectors_test.dart. Do not edit;')
    ..writeln('// regenerate with:')
    ..writeln(
      '//   UPDATE_VECTORS=1 flutter test test/band_sync_vectors_test.dart',
    )
    ..writeln('#pragma once')
    ..writeln()
    ..writeln('#include <stdint.h>')
    ..writeln()
    ..writeln('struct BandSyncVector {')
    ..writeln('  const char* name;')
    ..writeln('  const char* uuid;  // as the app advertises it, byte 0 first')
    ..writeln('  // Over the air (little-endian, as in the advertisement).')
    ..writeln('  uint8_t air[16];')
    ..writeln('  bool valid;')
    ..writeln('  uint16_t sessionId;')
    ..writeln('  uint8_t sequence;')
    ..writeln('  bool playing, freeRunning, rushing;')
    ..writeln('  uint8_t drift;  // 0 none, 1 on, 2 drifting, 3 off')
    ..writeln('  int16_t songIndex;  // -1 = none')
    ..writeln('  uint16_t target10, heard10;  // BPM x 10, 0 = none')
    ..writeln('  uint8_t confidence;  // x 255')
    ..writeln('  uint16_t detailsVersion;')
    ..writeln('};')
    ..writeln()
    ..writeln('static const BandSyncVector kBandSyncVectors[] = {');
  for (final v in _vectors()) {
    final air = bandSyncUuidToPayload(v.uuid)!.reversed.map(_hex).join(', ');
    final s = v.state;
    b
      ..writeln('    {"${v.name}", "${v.uuid}",')
      ..writeln('     {$air},');
    if (s == null) {
      b.writeln('     false, 0, 0, false, false, false, 0, -1, 0, 0, 0, 0},');
    } else {
      final target = s.targetBpm == null ? 0 : (s.targetBpm! * 10).round();
      final heard = s.detectedBpm == null ? 0 : (s.detectedBpm! * 10).round();
      b
        ..writeln(
          '     true, ${_hex(s.sessionId)}, ${s.sequence}, '
          '${_cBool(s.metronomePlaying)}, ${_cBool(s.freeRunning)}, '
          '${_cBool(s.rushing)}, ${_drift(s.drift)},',
        )
        ..writeln(
          '     ${s.songIndex ?? -1}, $target, $heard, '
          '${(s.confidence * 255).round()}, ${_hex(s.detailsVersion)}},',
        );
    }
  }
  b
    ..writeln('};')
    ..writeln()
    ..writeln(
      'static const int kBandSyncVectorCount =\n'
      '    sizeof(kBandSyncVectors) / sizeof(kBandSyncVectors[0]);',
    );
  return b.toString();
}

void main() {
  test('vectors decode as their names say', () {
    final byName = {for (final v in _vectors()) v.name: v};
    expect(byName['full']!.state!.detectedBpm, closeTo(121.4, 1e-9));
    expect(byName['empty_free_running']!.state!.songIndex, isNull);
    for (final n in ['bad_check', 'wrong_magic', 'newer_version']) {
      expect(decodeBandSyncUuid(byName[n]!.uuid), isNull, reason: n);
    }
  });

  test('firmware header is up to date', () {
    final file = File(_headerPath);
    final expected = renderHeader();
    if (Platform.environment['UPDATE_VECTORS'] == '1') {
      file.writeAsStringSync(expected);
    }
    expect(
      file.existsSync() ? file.readAsStringSync() : null,
      expected,
      reason:
          '$_headerPath is out of date; run '
          'UPDATE_VECTORS=1 flutter test test/band_sync_vectors_test.dart',
    );
  });
}
